NAMES = ("tree", "oak_tree", "willow_tree", "maple_tree", "yew_tree", "magic_tree", "glade_tree")

# Fairy Glade painted trees share the oak canopy footprint for click/beside checks.
for _qi in range(5):
    _MASK[("glade_tree", _qi)] = _MASK[("oak_tree", _qi)]


def bind_tiles(tile_to_name):
    _TILE_NAME.clear()
    _TILE_NAME.update(tile_to_name)


def _size_q(x, y):
    """Same size step as hd_trees.draw."""
    hsh = (int(x) * 73856093) ^ (int(y) * 19349663)
    return (((hsh ^ (hsh >> 11)) & 0xFF) >> 1) % 5


def mask(name, x, y):
    return _MASK.get((name, _size_q(x, y)), ())


def covers(name, trunk_x, trunk_y, x, y):
    """True when this tile contains opaque pixels of the painted sprite."""
    return (int(x) - int(trunk_x), int(y) - int(trunk_y)) in _MASK.get(
        (name, _size_q(trunk_x, trunk_y)), ()
    )


def beside(name, trunk_x, trunk_y, x, y):
    """True when (x, y) is next to the trunk or next to the painted footprint."""
    if max(abs(int(x) - int(trunk_x)), abs(int(y) - int(trunk_y))) <= 1:
        return True
    px, py = int(x), int(y)
    for dx, dy in mask(name, trunk_x, trunk_y):
        if max(abs(px - (int(trunk_x) + dx)), abs(py - (int(trunk_y) + dy))) <= 1:
            return True
    return False


def grass_blocked(grid, grass):
    """Grass tiles the painted sprite covers. The trunk tile is already blocked."""
    if not _TILE_NAME or not grid:
        return frozenset()
    height, width = len(grid), len(grid[0])
    blocked = set()
    for y in range(height):
        row = grid[y]
        for x in range(width):
            name = _TILE_NAME.get(row[x])
            if not name:
                continue
            for dx, dy in mask(name, x, y):
                nx, ny = x + dx, y + dy
                if 0 <= nx < width and 0 <= ny < height and grid[ny][nx] == grass:
                    blocked.add((nx, ny))
    return frozenset(blocked)


def trunk_at(nodes, x, y):
    """Closest live tree whose sprite covers (x, y). nodes is (tx, ty, name)."""
    best = None
    best_d = 99
    ix, iy = int(x), int(y)
    for tx, ty, name in nodes:
        if name not in NAMES:
            continue
        if max(abs(tx - ix), abs(ty - iy)) > 8:
            continue
        if not covers(name, tx, ty, ix, iy):
            continue
        dist = max(abs(tx - ix), abs(ty - iy))
        if dist < best_d:
            best = (int(tx), int(ty))
            best_d = dist
    return best
